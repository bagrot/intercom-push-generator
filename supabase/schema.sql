create extension if not exists pg_trgm with schema extensions;

create table if not exists public.addresses (
  id bigint generated by default as identity primary key,
  address text not null unique,
  created_at timestamptz not null default now()
);

create index if not exists addresses_search_idx
  on public.addresses using gin (lower(address) extensions.gin_trgm_ops);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'user' check (role in ('user', 'admin', 'developer')),
  created_at timestamptz not null default now()
);

create table if not exists public.scenario_templates (
  scenario_id text primary key,
  template jsonb not null,
  active boolean not null default true,
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.template_versions (
  id uuid primary key default gen_random_uuid(),
  scenario_id text not null,
  template jsonb not null,
  saved_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists template_versions_scenario_created_idx
  on public.template_versions (scenario_id, created_at desc);

alter table public.addresses enable row level security;
alter table public.profiles enable row level security;
alter table public.scenario_templates enable row level security;
alter table public.template_versions enable row level security;

revoke all on public.addresses from anon, authenticated;
revoke all on public.profiles from anon, authenticated;
revoke all on public.scenario_templates from anon, authenticated;
revoke all on public.template_versions from anon, authenticated;

grant select on public.addresses to authenticated;
grant select, insert on public.profiles to authenticated;
grant select, insert, update on public.scenario_templates to authenticated;
grant select, insert on public.template_versions to authenticated;

drop policy if exists "authenticated users read addresses" on public.addresses;
create policy "authenticated users read addresses"
  on public.addresses for select to authenticated using (true);

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile"
  on public.profiles for select to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "users create own profile" on public.profiles;
create policy "users create own profile"
  on public.profiles for insert to authenticated
  with check ((select auth.uid()) = id and role = 'user');

drop policy if exists "authenticated users read templates" on public.scenario_templates;
create policy "authenticated users read templates"
  on public.scenario_templates for select to authenticated using (true);

drop policy if exists "admins insert templates" on public.scenario_templates;
create policy "admins insert templates"
  on public.scenario_templates for insert to authenticated
  with check (
    exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'developer')
    )
  );

drop policy if exists "admins update templates" on public.scenario_templates;
create policy "admins update templates"
  on public.scenario_templates for update to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'developer')
    )
  )
  with check (
    exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'developer')
    )
  );

drop policy if exists "authenticated users read template history" on public.template_versions;
create policy "authenticated users read template history"
  on public.template_versions for select to authenticated using (true);

drop policy if exists "admins add template history" on public.template_versions;
create policy "admins add template history"
  on public.template_versions for insert to authenticated
  with check (
    saved_by = (select auth.uid())
    and exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'developer')
    )
  );

create or replace function public.search_addresses(
  search_term text default '',
  result_limit integer default 40
)
returns table (id bigint, address text)
language sql
stable
security invoker
set search_path = ''
as $$
  select a.id, a.address
  from public.addresses a
  where coalesce(trim(search_term), '') = ''
     or lower(a.address) like '%' || lower(trim(search_term)) || '%'
  order by
    case when lower(a.address) like lower(trim(search_term)) || '%' then 0 else 1 end,
    a.address
  limit least(greatest(result_limit, 1), 100);
$$;

revoke all on function public.search_addresses(text, integer) from public, anon;
grant execute on function public.search_addresses(text, integer) to authenticated;
